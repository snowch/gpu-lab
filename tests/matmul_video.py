import json
from playwright.sync_api import expect

def check_matmul_video(browser,url,root,errors):
    media=json.loads((root/'content/matmul-media.json').read_text())
    for width in [390,820,1440]:
        for theme in ['light','dark']:
            context=browser.new_context(viewport={'width':width,'height':1000},color_scheme=theme,service_workers='block')
            page=context.new_page();page.on('pageerror',lambda error:errors.append(str(error)))
            page.goto(url+'lessons/matmul.html?keep=video')
            page.locator('#matrix-reuse-tile').select_option('1')
            page.locator('#matrix-reuse [data-run]').click()
            page.locator('#matrix-reuse [data-next]').click()
            result=page.locator('#matrix-reuse [data-visual-output]').inner_text()
            expect(page.locator('#matrix-dot [data-results]')).to_be_hidden()
            expect(page.locator('#matmul-watch')).to_contain_text('Watch chapter recap')
            assert page.locator('#matmul-recording-link').evaluate('el=>el.previousElementSibling.matches(".continuation-transfer")&&el.nextElementSibling.matches(".desktop-links")')
            link=page.locator('#matmul-watch')
            link.evaluate("el=>scrollTo({top:scrollY+el.getBoundingClientRect().top-250,behavior:'instant'})")
            position=page.evaluate('scrollY');link.focus();page.keyboard.press('Enter')
            expect(page.locator('h1')).to_have_text('How matrix tiles reuse inputs')
            expect(page.locator('.sidebar')).to_be_hidden()
            expect(page.locator('#lesson-complete,.chapter-references')).to_have_count(0)
            video=page.locator('#matmul-video')
            for attr in ['controls','playsinline']:expect(video).to_have_attribute(attr,'')
            expect(video).to_have_attribute('preload','none')
            assert video.get_attribute('autoplay') is None
            expect(video.locator('track')).to_have_attribute('kind','captions')
            expect(video.locator('track')).to_have_attribute('srclang','en')
            expect(video.locator('track')).to_have_attribute('default','')
            page.locator('#matmul-transcript summary').focus();page.keyboard.press('Enter')
            expect(page.locator('#matmul-transcript section')).to_have_count(10)
            expect(page.locator('#matmul-transcript')).to_contain_text('Each thread retains its own partial output sum')
            video.evaluate('v=>v.load()')
            page.wait_for_function('document.querySelector("#matmul-video").readyState>=1')
            assert abs(video.evaluate('v=>v.duration')-media['durationSeconds'])<1
            assert video.evaluate('v=>v.videoWidth')==3840
            video.evaluate('v=>{v.currentTime=45;v.playbackRate=1.25;v.muted=true;v.play()}')
            page.wait_for_function('document.querySelector("#matmul-video").currentTime>45.1')
            video.evaluate('v=>v.pause()')
            page.wait_for_function('document.querySelector("#matmul-video").textTracks[0].cues?.length>0')
            assert video.evaluate('v=>v.textTracks[0].mode')=='showing'
            assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
            page.locator('#matmul-recording').screenshot(path=str(root/f'test-results/matmul-video-{width}-{theme}.png'),style='.topbar{position:static!important}')
            page.locator('#matmul-return').click()
            expect(page).to_have_url(url+'lessons/matmul.html?keep=video')
            expect(page.locator('#matrix-reuse-tile')).to_have_value('1')
            expect(page.locator('#matrix-reuse [data-visual-output]')).to_have_text(result,use_inner_text=True)
            expect(page.locator('#matrix-dot [data-results]')).to_be_hidden()
            page.wait_for_function('(position)=>Math.abs(scrollY-position)<8',arg=position)
            expect(page.locator('#matmul-watch')).to_be_focused()
            page.locator('#matmul-watch').click()
            page.wait_for_function('document.querySelector("#matmul-video").currentTime>=45')
            assert page.locator('#matmul-video').evaluate('v=>v.paused&&v.playbackRate===1.25')
            expect(page.locator('#matmul-transcript')).to_have_attribute('open','')
            context.close()
    context=browser.new_context(java_script_enabled=False,viewport={'width':390,'height':1000})
    page=context.new_page();page.goto(url+'lessons/matmul-video.html')
    expect(page.locator('#matmul-video')).to_be_visible()
    page.locator('#matmul-transcript summary').click()
    expect(page.locator('#matmul-transcript')).to_contain_text('Sharing within one block does not automatically supply another block')
    expect(page.locator('#matmul-return')).to_have_attribute('href','matmul.html#matmul-recording-link')
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    context.close()
    print('PASS: Chapter 10 recording playback, captions, keyboard return, saved tile/trace/video state, six layouts/themes and no-JavaScript transcript')
