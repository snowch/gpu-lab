from pathlib import Path
from playwright.sync_api import expect
from version_check import mock_version

def hello_flow(page, url):
    page.goto(url + 'lessons/hello.html')
    expect(page.locator('h1')).to_have_text('Many numbers, one calculation')
    visible=page.locator('main').inner_text()
    assert '__global__' not in visible and 'blockIdx' not in visible and 'float*' not in visible
    expect(page.locator('#hello-cuda-section')).to_be_hidden()
    expect(page.locator('#hello-map .hello-thread')).to_have_count(4)
    page.locator('#hello-run').click()
    expect(page.locator('#hello-output')).to_have_text('Output: [2, 4, 6, 8]')
    page.locator('#hello-factor').fill('')
    expect(page.locator('#hello-next')).to_be_hidden()
    page.locator('#hello-run').click()
    expect(page.locator('#hello-output')).to_contain_text('Enter a multiplier')
    page.locator('#hello-factor').fill('3')
    page.locator('#hello-run').click()
    expect(page.locator('#hello-output')).to_have_text('Output: [3, 6, 9, 12]')
    expect(page.locator('#hello-map .hello-thread').last).to_contain_text('12')
    page.locator('#hello-next').click()
    expect(page.locator('#hello-cuda-section')).to_be_visible()
    expect(page.locator('#hello-group-code')).to_be_hidden()
    page.locator('#hello-map button').nth(2).focus()
    page.keyboard.press('Enter')
    expect(page.locator('#hello-index')).to_contain_text('i = 2')
    expect(page.locator('#hello-selected-code')).to_have_text('output[2] = input[2] * 3;')
    page.locator('#hello-run').click()
    page.locator('#hello-next').click()
    expect(page.locator('#hello-map h3')).to_have_count(2)
    page.locator('#hello-map button').nth(3).click()
    expect(page.locator('#hello-index')).to_contain_text('block 1 × 2 threads per block + position 1 = index 3')
    page.locator('#hello-run').click()
    page.locator('#hello-next').click()
    expect(page.locator('#hello-map button')).to_have_count(8)
    page.locator('#hello-run').click()
    expect(page.locator('#hello-map [data-state="skip"]')).to_have_count(3)
    page.locator('#hello-guard').uncheck()
    expect(page.locator('#hello-line')).not_to_contain_text('if')
    page.locator('#hello-run').click()
    expect(page.locator('#hello-map [data-state="invalid"]')).to_have_count(3)
    expect(page.locator('#hello-output')).to_contain_text('3 threads would access outside')
    expect(page.locator('#hello-next')).to_be_hidden()
    page.locator('#hello-guard').check()
    page.locator('#hello-run').click()
    page.locator('#hello-next').click()
    expect(page.locator('#hello-complete')).to_be_visible()
    expect(page.locator('#hello-full')).to_contain_text('__global__')
    expect(page.locator('#hello-python')).to_contain_text('device="cuda"')
    page.locator('#hello-run').click()
    expect(page.locator('#hello-output')).to_have_text('Output: [3, 6, 9, 12, 15]')
    expect(page.locator('#hello-repair')).to_be_visible()
    page.get_by_text('Run the CUDA example on an NVIDIA GPU',exact=True).click()
    with page.expect_download() as downloaded:
        page.locator('#hello-download').click()
    source=Path(downloaded.value.path()).read_text()
    assert 'input[i] * 3.0f' in source and 'cudaDeviceSynchronize' in source
    page.locator('#hello-back').click()
    expect(page.locator('#hello-factor')).to_have_value('3')
    expect(page.locator('#hello-complete')).to_be_hidden()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')

def check_hello(browser,url,root,errors):
    for width in [360,820,1440]:
        for theme in ['light','dark']:
            context=browser.new_context(viewport={'width':width,'height':900},color_scheme=theme)
            mock_version(context)
            page=context.new_page()
            page.on('pageerror',lambda e:errors.append(str(e)))
            hello_flow(page,url)
            page.screenshot(path=str(root/f'test-results/hello-bounds-{width}-{theme}.png'),full_page=True,style='.topbar {position:static!important}')
            page.goto(url+'lessons/hello.html')
            page.locator('#hello-run').click()
            expect(page.locator('#hello-output')).to_have_text('Output: [2, 4, 6, 8]')
            page.screenshot(path=str(root/f'test-results/hello-{width}-{theme}.png'),full_page=True,style='.topbar {position:static!important}')
            context.close()
    context=browser.new_context(java_script_enabled=False)
    page=context.new_page();page.goto(url+'lessons/hello.html')
    expect(page.locator('noscript .notice')).to_contain_text('Doubling [1, 2, 3, 4]')
    context.close()
    print('PASS: concept-first progression, computed thread map, keyboard selection, bounds diagnostics, CUDA download and responsive layout')
