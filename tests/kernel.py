"""The learner repairs and diagnoses a kernel on desktop and phones."""
from playwright.sync_api import expect
from version_check import mock_version


def check_kernel(browser, base_url, root, errors):
    for width in [1440, 820, 390, 360]:
        for theme in ['light', 'dark']:
            context = browser.new_context(viewport={'width': width, 'height': 1000}, color_scheme=theme)
            mock_version(context)
            page = context.new_page()
            page.on('pageerror', lambda error: errors.append(str(error)))
            page.goto(base_url + 'lessons/kernel.html')
            expect(page.locator('h1')).to_have_text('Repair a kernel')
            page.locator('#reset-kernel').click()
            page.locator('#run-model').click()
            expect(page.locator('#kernel-status')).to_contain_text('0 of 3')
            expect(page.locator('#kernel-cases')).to_contain_text('expected 1, got — (unwritten)')
            page.locator('#kernel-index').select_option('global')
            expect(page.locator('#kernel-results')).to_be_hidden()
            expect(page.locator('#kernel-source')).to_contain_text('let i = global_id.x;')
            page.locator('#run-model').click()
            expect(page.locator('#kernel-status')).to_contain_text('3 of 3')
            page.get_by_role('button', name='Inspect 35', exact=True).click()
            page.locator('#trace-end').click()
            expect(page.locator('#kernel-event')).to_contain_text('63 < 35: false')
            expect(page.locator('#kernel-output .kernel-cell')).to_have_count(35)
            expect(page.locator('#kernel-output .kernel-cell').last).to_contain_text('35')
            page.locator('#trace-start').click()
            page.locator('#trace-next').click()
            expect(page.locator('#kernel-event')).to_contain_text('0 < 35: true')
            page.locator('#trace-next').click()
            expect(page.locator('#kernel-event')).to_contain_text('Read x[0] = 0.5 at byte offset 0')
            expect(page.locator('#kernel-input .active')).to_have_count(1)
            page.locator('#kernel-guard').select_option('no')
            page.locator('#run-model').click()
            expect(page.locator('#kernel-cases')).to_contain_text('outside 8 elements')
            page.locator('#kernel-guard').select_option('yes')
            page.locator('#kernel-index').select_option('local')
            page.locator('#run-model').click()
            expect(page.locator('#kernel-status')).to_contain_text('2 of 3')
            expect(page.locator('#kernel-cases')).to_contain_text('different workgroups')
            page.locator('#kernel-index').select_option('global')
            page.locator('#kernel-operation').select_option('add')
            page.locator('#run-model').click()
            expect(page.locator('#kernel-status')).to_contain_text('0 of 3')
            page.locator('#challenge-choice').select_option('3')
            page.locator('#start-challenge').click()
            page.locator('#check-challenge').click()
            expect(page.locator('#challenge-feedback')).to_contain_text('prediction first')
            page.locator('#challenge-prediction').fill('40')
            page.locator('#check-prediction').click()
            expect(page.locator('#prediction-feedback')).to_contain_text('Prediction matches')
            page.locator('#kernel-index').select_option('global')
            page.locator('#kernel-guard').select_option('yes')
            page.locator('#kernel-operation').select_option('vector-add')
            page.locator('#challenge-answer').select_option('1')
            page.locator('#check-challenge').click()
            expect(page.locator('#challenge-feedback')).to_contain_text('Revisit your explanation')
            page.locator('#challenge-answer').select_option('0')
            page.locator('#check-challenge').click()
            expect(page.locator('#challenge-feedback')).to_contain_text('Challenge complete')
            page.get_by_role('button', name='Inspect 35', exact=True).click()
            page.locator('#invocation-map button').nth(34).click()
            expect(page.locator('#kernel-state')).to_contain_text('34')
            expect(page.locator('#second-input-panel')).to_be_visible()
            page.locator('#kernel-size').select_option('16')
            expect(page.locator('#challenge-feedback')).to_have_text('')
            page.locator('#run-model').click()
            expect(page.locator('#kernel-status')).to_contain_text('3 of 3')
            page.locator('#kernel-operation').select_option('add')
            page.reload()
            expect(page.locator('#kernel-operation')).to_have_value('add')
            expect(page.locator('#kernel-results')).to_be_hidden()
            page.screenshot(path=str(root / f'test-results/kernel-{width}-{theme}.png'), full_page=True, style=".topbar { position:static!important; }")
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Kernel prototype overflows'
            page.locator('#reset-kernel').click()
            expect(page.locator('#kernel-index')).to_have_value('next')
            expect(page.locator('#kernel-operation')).to_have_value('multiply')
            context.close()
    context = browser.new_context()
    mock_version(context)
    context.add_init_script("Object.defineProperty(navigator, 'gpu', {value: undefined, configurable: true})")
    page = context.new_page()
    page.goto(base_url + 'lessons/kernel.html')
    expect(page.locator('#run-gpu')).to_be_disabled()
    expect(page.locator('#gpu-support')).to_contain_text('unavailable')
    page.locator('#run-model').click()
    expect(page.locator('#kernel-results')).to_be_visible()
    context.close()
    context = browser.new_context(java_script_enabled=False)
    page = context.new_page()
    page.goto(base_url + 'lessons/kernel.html')
    expect(page.locator('noscript .notice')).to_contain_text('Enable JavaScript')
    expect(page.locator('#task-title')).to_have_text('Your task: pass all three checks')
    context.close()
    print('PASS: kernel repair, failures, source edits, replay, persistence, mobile layout and unsupported-WebGPU fallback')
